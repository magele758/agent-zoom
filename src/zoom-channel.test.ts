import assert from "node:assert/strict";
import { test } from "node:test";
import { openStore } from "./server/logic.ts";
import { channelMessages } from "./server/zoom-channel.ts";

test("频道问题在消息列表中分别答复，答复沿原频道送回，重发仅通知一次", () => {
  const store = openStore(":memory:");
  const user = store.userBySession(store.session("消息列表验收").token)!;
  assert.ok(user.type === "user");
  const room = store.createRoom(user, "执行器", "", { project: "OPC OS" });
  const enroll = (handle: string) => {
    const member = store.agentByToken(store.enroll(store.createJoinCode(user, room.id).code, handle, "native").token);
    assert.ok(member?.type === "agent");
    return member;
  };
  const agent = enroll("worker");
  const other = enroll("other");
  const task = store.postMessage(user, room.id, { kind: "instruction", body: "@worker 修复重试" }).task!;
  store.claim(agent, task.id, "implementer");
  const question = String(store.postMessage(agent, room.id, { kind: "blocked", body: "采用哪个版本？", taskId: task.id }).message.id);
  const otherQ = String(store.postMessage(agent, room.id, { kind: "question", body: "保留旧版多久？", taskId: task.id }).message.id);
  const peer = store.postMessage(agent, room.id, { kind: "question", body: "@other 测试准备好了？", taskId: task.id });
  const privatePeer = store.ask(agent, { handles: [other.handle], body: "你的本地目录在哪里？" });
  const outsider = store.userBySession(store.session("另一个工作室").token)!;
  assert.ok(outsider.type === "user");
  assert.deepEqual(channelMessages(store, outsider), channelMessages(store, user));
  const feed = channelMessages(store, user);
  assert.equal(feed.filter(row => row.pending).length, 2);
  assert.equal(feed.find(row => row.body === "采用哪个版本？")?.folder, "OPC OS/执行器");
  assert.equal(feed.find(row => row.id === "channel:" + peer.message.id)?.pending, false);
  assert.equal(feed.find(row => row.id === "channel:" + privatePeer.message.id)?.pending, false);
  const reply = { kind: "chat", body: "沿用当前版本", replyTo: question };
  const notificationCount = () => store.inboxAfter(agent.id, 0).filter(event => event.summary === reply.body).length;
  assert.equal(outsider.id, user.id);
  assert.throws(() => store.postMessage(user, room.id, { ...reply, taskId: "unrelated" }));
  const message = store.postMessage(user, room.id, reply).message;
  assert.equal(message.taskId, task.id);
  const count = notificationCount();
  assert.equal(count, 1);
  assert.equal(store.postMessage(user, room.id, reply).message.id, message.id);
  assert.equal(notificationCount(), count);
  assert.throws(() => store.postMessage(user, room.id, { ...reply, body: "另一份意见" }));
  const updated = channelMessages(store, user);
  assert.deepEqual(updated.filter(row => row.pending).map(row => row.id), ["channel:" + otherQ]);
  assert.equal(updated.find(row => row.replyTo === "channel:" + question)?.body, reply.body);
  store.forceDone(user, task.id);
  assert.equal(channelMessages(store, user).filter(row => row.pending).length, 0);
  assert.ok(channelMessages(store, user).some(row => row.taskId === "channel:" + task.id && row.kind === "completed"));
  assert.throws(() => store.postMessage(user, room.id, { ...reply, replyTo: otherQ }), /已经结束/);
  assert.equal(store.postMessage(user, room.id, reply).message.id, message.id);
  store.db.close();
});
